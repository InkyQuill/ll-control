//! Build helper binary for the ll-control workspace.
//!
//! Run from the workspace root, e.g. `cargo run -p xtask -- gen-udev`.

use std::path::Path;

use anyhow::{Context, Result};
use clap::Parser;

#[derive(Parser)]
#[command(version, about = "ll-control build helpers")]
enum Cmd {
    /// Generate `packaging/udev/70-lianli-hid.rules` from the device-family table.
    GenUdev,
}

fn main() -> Result<()> {
    match Cmd::parse() {
        Cmd::GenUdev => gen_udev(),
    }
}

/// Devices the package must make visible to the active session.
///
/// Phase 1 scope: only Galahad II LCDV2 (VID `0x0416`, PID `0x7395`).
/// Phase 3+ this should be sourced from the device-family registry in
/// `llcontrol-hid` so that adding a family in one place propagates here
/// automatically.
const DEVICES: &[(&str, u16, u16)] = &[("Galahad II LCDV2", 0x0416, 0x7395)];

/// Render the packaged hidraw rule.
///
/// Access is `TAG+="uaccess"` for the active seat, with mode `0660`. The
/// rule deliberately names no group: udev discards a whole rule when
/// `GROUP=` does not resolve, which previously dropped this device on Arch
/// because `plugdev` is not created by the package.
fn render_udev(entries: &[(&str, u16, u16)]) -> String {
    let mut rule = String::from(
        "# AUTO-GENERATED by xtask gen-udev. Do not edit by hand.\n\
         # Session access is uaccess. The package creates no distribution group for this node.\n",
    );
    for (name, vid, pid) in entries {
        rule.push_str(&format!("# {name}\n"));
        rule.push_str(&format!(
            "SUBSYSTEM==\"hidraw\", ATTRS{{idVendor}}==\"{vid:04x}\", ATTRS{{idProduct}}==\"{pid:04x}\", \\\n",
        ));
        rule.push_str("  TAG+=\"uaccess\", MODE=\"0660\"\n");
    }
    rule
}

/// Generate the udev rules file granting the active session hidraw access
/// to the supported Lian-Li devices.
fn gen_udev() -> Result<()> {
    let rule = render_udev(DEVICES);
    let out_path = Path::new("packaging/udev/70-lianli-hid.rules");
    if let Some(parent) = out_path.parent() {
        std::fs::create_dir_all(parent)
            .with_context(|| format!("failed to create directory {}", parent.display()))?;
    }
    std::fs::write(out_path, rule)
        .with_context(|| format!("failed to write {}", out_path.display()))?;
    println!("wrote {}", out_path.display());
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::render_udev;

    #[test]
    fn packaged_rule_registers_galahad_for_the_active_session() {
        let rule = render_udev(&[("Galahad II LCDV2", 0x0416, 0x7395)]);
        assert!(rule.contains("ATTRS{idVendor}==\"0416\""));
        assert!(rule.contains("ATTRS{idProduct}==\"7395\""));
        assert!(rule.contains("TAG+=\"uaccess\""));
        assert!(rule.contains("MODE=\"0660\""));
        assert!(
            !rule.contains("GROUP="),
            "an unknown group makes udev ignore the rule, including uaccess"
        );
    }
}
