#!/usr/bin/env python3
"""Original 24-second seamless ambient background. Requires FFmpeg/libx264."""
from pathlib import Path
import math
import re
import subprocess

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'crates/lconnect-daemon/assets/defaults'
OUT.mkdir(parents=True, exist_ok=True)
path = OUT / 'aurora-v1.h264'
cmd = ['ffmpeg','-nostdin','-v','error','-y','-f','rawvideo','-pix_fmt','rgb24','-s','120x120','-r','24','-i','pipe:0','-vf','scale=480:480:flags=lanczos','-an','-c:v','libx264','-threads','1','-preset','ultrafast','-tune','zerolatency','-profile:v','baseline','-level:v','3.0','-pix_fmt','yuv420p','-crf','23','-g','24','-keyint_min','24','-sc_threshold','0','-bf','0','-x264-params','aud=1:repeat-headers=1','-f','h264',str(path)]
proc = subprocess.Popen(cmd, stdin=subprocess.PIPE)
try:
    for frame in range(576):
        phase = 2 * math.pi * frame / 576
        cx, cy = 60 + 32 * math.cos(phase), 60 + 32 * math.sin(phase)
        pixels = bytearray()
        for y in range(120):
            for x in range(120):
                a = max(0, 1 - math.hypot(x-cx, y-cy)/100)**2
                b = max(0, 1 - math.hypot(x-(120-cx), y-(120-cy))/100)**2
                pixels.extend((round(9+34*b), round(16+50*a), round(29+50*a+34*b)))
        proc.stdin.write(pixels)
finally:
    proc.stdin.close()
if proc.wait() != 0:
    raise SystemExit('FFmpeg failed')
encoded = path.read_bytes()
nals = [(m.start(), encoded[m.end()] & 31) for m in re.finditer(b'\x00\x00(?:\x00)?\x01',encoded)]
offsets = [start for start, kind in nals if kind == 9]
assert len(offsets)==576 and offsets[0]==0
ends = offsets[1:]+[len(encoded)]
units=[]
for start,end in zip(offsets,ends):
    assert 0<end-start<=128*1024
    key=any(kind==5 for pos,kind in nals if start<=pos<end)
    units.append(f'    ({start}, {end}, {str(key).lower()}),')
(OUT/'aurora-v1-index.rs').write_text('// Generated by tools/generate-lcd-default-video.py. Do not edit.\n&[\n'+'\n'.join(units)+'\n]\n')
print(f'{len(offsets)} frames, {len(encoded)} bytes')
