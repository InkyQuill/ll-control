// Independent offline interpretation of the versioned shader assembly.
// These vectors are not GPU/WPF raster qualification; see editor-shaders evidence.
#[test]
fn point_filters_match_disassembled_shader_vectors_within_one_level() {
    let cases = [
        ([255, 0, 0, 255], [120, 0, 0, 0], [0, 255, 0, 255]),
        ([255, 0, 0, 128], [240, 0, 0, 0], [0, 0, 255, 128]),
        ([255, 0, 0, 255], [0, -25, 0, 0], [76, 76, 76, 255]),
        ([0, 255, 0, 255], [0, -25, 0, 0], [150, 150, 150, 255]),
        ([0, 0, 255, 255], [0, -25, 0, 0], [29, 29, 29, 255]),
        ([40, 100, 180, 128], [0, 0, 50, 0], [167, 227, 255, 128]),
        ([40, 100, 180, 128], [0, 0, 0, -100], [128, 128, 128, 128]),
        ([160, 80, 25, 200], [45, 50, -20, 60], [93, 196, 0, 200]),
        (
            [22, 150, 210, 255],
            [315, -15, 15, -35],
            [145, 194, 173, 255],
        ),
        ([190, 80, 90, 80], [90, 75, 10, 25], [108, 255, 0, 80]),
        ([128, 128, 128, 128], [270, 75, 0, 0], [128, 128, 128, 128]),
        ([0, 0, 0, 255], [90, 0, 100, 100], [128, 128, 128, 255]),
    ];
    for (rgba, controls, expected) in cases.into_iter().chain(POINT_VECTORS) {
        let [hue, saturation, brightness, contrast] = controls;
        let filter = ColorFilters {
            hue: hue as f32,
            saturation: saturation as f32,
            brightness: brightness as f32,
            contrast: contrast as f32,
            ..Default::default()
        };
        let mut image = RgbaImage::from_pixel(1, 1, Rgba(rgba));
        filter.apply(&mut image).unwrap();
        for (actual, expected) in image.get_pixel(0, 0).0.into_iter().zip(expected) {
            assert!(
                actual.abs_diff(expected) <= 1,
                "{rgba:?} {controls:?}: {:?} != {expected:?}",
                image.get_pixel(0, 0)
            );
        }
    }
}
#[test]
fn neutral_preserves_bytes_and_transparent_non_neutral_pixels_remain_transparent() {
    let mut image = RgbaImage::from_pixel(1, 1, Rgba([19, 83, 144, 0]));
    ColorFilters::default().apply(&mut image).unwrap();
    assert_eq!(image.get_pixel(0, 0).0, [19, 83, 144, 0]);
    ColorFilters {
        brightness: 100.,
        ..Default::default()
    }
    .apply(&mut image)
    .unwrap();
    assert_eq!(image.get_pixel(0, 0).0, [0; 4]);
}
#[test]
fn invalid_filter_controls_fail_before_touching_pixels() {
    for filter in [
        ColorFilters {
            hue: f32::NAN,
            ..Default::default()
        },
        ColorFilters {
            hue: 361.,
            ..Default::default()
        },
        ColorFilters {
            saturation: -26.,
            ..Default::default()
        },
        ColorFilters {
            brightness: f32::INFINITY,
            ..Default::default()
        },
        ColorFilters {
            contrast: -101.,
            ..Default::default()
        },
    ] {
        let mut image = RgbaImage::from_pixel(1, 1, Rgba([12, 34, 56, 255]));
        assert!(filter.apply(&mut image).is_err());
        assert_eq!(image.get_pixel(0, 0).0, [12, 34, 56, 255]);
    }
}
#[test]
fn encoded_editor_result_contains_color_edits_and_geometry() {
    let mut bytes = Cursor::new(Vec::new());
    DynamicImage::ImageRgba8(RgbaImage::from_pixel(20, 40, Rgba([255, 0, 0, 128])))
        .write_to(&mut bytes, ImageFormat::Png)
        .unwrap();
    let output = llcontrol_image::editor::prepare_edited(
        &bytes.into_inner(),
        None,
        &[llcontrol_image::editor::Transform::RotateRight],
        ColorFilters {
            hue: 120.,
            ..Default::default()
        },
    )
    .unwrap();
    let frame = image::load_from_memory(&output).unwrap().into_rgba8();
    assert_eq!(frame.dimensions(), (480, 480));
    assert_eq!(frame.get_pixel(240, 240).0, [0, 255, 0, 128]);
}

