//! Private-bus FileChooser fixture for native archive acceptance only.
use std::{collections::HashMap, io::Write, path::PathBuf};
use zbus::{
    zvariant::{OwnedObjectPath, OwnedValue, Value},
    Connection,
};
struct Portal {
    root: PathBuf,
}
struct Request;
#[zbus::interface(name = "org.freedesktop.portal.Request")]
impl Request {
    fn close(&self) {}
}
impl Portal {
    async fn choose(
        &self,
        method: &str,
        title: &str,
        options: HashMap<String, OwnedValue>,
        connection: &Connection,
        header: zbus::message::Header<'_>,
    ) -> zbus::fdo::Result<OwnedObjectPath> {
        let token = <&str>::try_from(options.get("handle_token").unwrap()).unwrap();
        let sender = header
            .sender()
            .unwrap()
            .as_str()
            .trim_start_matches(':')
            .replace('.', "_");
        let path = OwnedObjectPath::try_from(format!(
            "/org/freedesktop/portal/desktop/request/{sender}/{token}"
        ))
        .unwrap();
        connection
            .object_server()
            .at(path.clone(), Request)
            .await
            .unwrap();
        let file = self.root.join(
            if std::env::var("LLCONTROL_NATIVE_WINDOWS_PORTAL").as_deref() == Ok("1") {
                "source controls.zip"
            } else if std::env::var("LLCONTROL_NATIVE_GROUP_PORTAL").as_deref() == Ok("1") {
                "exported group.lcg"
            } else {
                "exported archive.lcp"
            },
        );
        let uri = url_string(&file);
        let mut log = std::fs::OpenOptions::new()
            .append(true)
            .create(true)
            .open(self.root.join("archive-portal-events.jsonl"))
            .unwrap();
        let filters: Vec<(String, Vec<(u32, String)>)> = options
            .get("filters")
            .unwrap()
            .try_clone()
            .unwrap()
            .try_into()
            .unwrap();
        writeln!(
            log,
            "{}",
            serde_json::json!({"method":method,"path":file,"title":title,"filters":filters})
        )
        .unwrap();
        connection
            .emit_signal(
                None::<&str>,
                path.clone(),
                "org.freedesktop.portal.Request",
                "Response",
                &(0u32, HashMap::from([("uris", Value::from(vec![uri]))])),
            )
            .await
            .unwrap();
        Ok(path)
    }
}
// Fixture root is generated by Python and contains only safe ASCII plus spaces.
fn url_string(path: &std::path::Path) -> String {
    format!("file://{}", path.to_str().unwrap().replace(' ', "%20"))
}
#[zbus::interface(name = "org.freedesktop.portal.FileChooser")]
impl Portal {
    async fn open_file(
        &self,
        _parent: &str,
        title: &str,
        options: HashMap<String, OwnedValue>,
        #[zbus(connection)] connection: &Connection,
        #[zbus(header)] header: zbus::message::Header<'_>,
    ) -> zbus::fdo::Result<OwnedObjectPath> {
        self.choose("OpenFile", title, options, connection, header)
            .await
    }
    async fn save_file(
        &self,
        _parent: &str,
        title: &str,
        options: HashMap<String, OwnedValue>,
        #[zbus(connection)] connection: &Connection,
        #[zbus(header)] header: zbus::message::Header<'_>,
    ) -> zbus::fdo::Result<OwnedObjectPath> {
        self.choose("SaveFile", title, options, connection, header)
            .await
    }
}
pub async fn start(root: PathBuf) -> anyhow::Result<Connection> {
    anyhow::ensure!(
        root.is_absolute() && root.join("fixture-marker").is_file(),
        "private fixture root required"
    );
    let connection = Connection::session().await?;
    connection
        .object_server()
        .at("/org/freedesktop/portal/desktop", Portal { root })
        .await?;
    connection
        .request_name("org.freedesktop.portal.Desktop")
        .await?;
    Ok(connection)
}
