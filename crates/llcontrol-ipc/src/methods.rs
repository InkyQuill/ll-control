//! Versioned RPC method registry shared by transport, native clients, and TypeScript.

use crate::{DeviceDescriptor, DisplaySettings, SensorReading};
use serde::{de::DeserializeOwned, Deserialize};
use serde_json::Value;

fn decode<T: DeserializeOwned>(value: Value) -> crate::Result<T> {
    serde_json::from_value(value)
        .map_err(|error| crate::IpcError::InvalidArgument(error.to_string()))
}

pub const RPC_CONTRACT_VERSION: u32 = 1;

#[derive(Clone, Copy, PartialEq, Eq)]
pub enum RequestShape {
    Empty,
    DisplaySettings,
}

#[derive(Clone, Copy, PartialEq, Eq)]
pub enum ResponseShape {
    DeviceList,
    SensorList,
    DisplaySettings,
}

pub struct RpcMethod {
    pub name: &'static str,
    pub version: u32,
    pub request: RequestShape,
    pub response: ResponseShape,
}

pub const LIST_DEVICES_NAME: &str = "list_devices";
pub const LIST_SENSORS_NAME: &str = "list_sensors";
pub const GET_DISPLAY_SETTINGS_NAME: &str = "get_display_settings";
pub const SET_DISPLAY_SETTINGS_NAME: &str = "set_display_settings";

pub const LIST_DEVICES: RpcMethod = RpcMethod {
    name: LIST_DEVICES_NAME,
    version: 1,
    request: RequestShape::Empty,
    response: ResponseShape::DeviceList,
};
pub const LIST_SENSORS: RpcMethod = RpcMethod {
    name: LIST_SENSORS_NAME,
    version: 1,
    request: RequestShape::Empty,
    response: ResponseShape::SensorList,
};
pub const GET_DISPLAY_SETTINGS: RpcMethod = RpcMethod {
    name: GET_DISPLAY_SETTINGS_NAME,
    version: 1,
    request: RequestShape::Empty,
    response: ResponseShape::DisplaySettings,
};
pub const SET_DISPLAY_SETTINGS: RpcMethod = RpcMethod {
    name: SET_DISPLAY_SETTINGS_NAME,
    version: 1,
    request: RequestShape::DisplaySettings,
    response: ResponseShape::DisplaySettings,
};

pub const METHODS: &[RpcMethod] = &[
    LIST_DEVICES,
    LIST_SENSORS,
    GET_DISPLAY_SETTINGS,
    SET_DISPLAY_SETTINGS,
];

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
pub struct EmptyParams {}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
pub struct SetDisplaySettingsParams {
    pub settings: DisplaySettings,
}

pub fn validate_request(method: &str, params: Value) -> crate::Result<()> {
    let registered = METHODS
        .iter()
        .find(|candidate| candidate.name == method)
        .ok_or_else(|| {
            crate::IpcError::InvalidArgument(format!("unregistered RPC method: {method}"))
        })?;
    match registered.request {
        RequestShape::Empty => {
            let _: EmptyParams = decode(params)?;
        }
        RequestShape::DisplaySettings => {
            let params: SetDisplaySettingsParams = decode(params)?;
            params.settings.validate()?;
        }
    }
    Ok(())
}

pub fn validate_response(method: &str, value: &Value) -> crate::Result<()> {
    let registered = METHODS
        .iter()
        .find(|candidate| candidate.name == method)
        .ok_or_else(|| {
            crate::IpcError::InvalidArgument(format!("unregistered RPC method: {method}"))
        })?;
    match registered.response {
        ResponseShape::DeviceList => {
            let _: Vec<DeviceDescriptor> = decode(value.clone())?;
        }
        ResponseShape::SensorList => {
            let _: Vec<SensorReading> = decode(value.clone())?;
        }
        ResponseShape::DisplaySettings => {
            let settings: DisplaySettings = decode(value.clone())?;
            settings.validate()?;
        }
    }
    Ok(())
}

pub fn typescript_contract() -> String {
    let mut output = String::from(
        "// Generated by crates/llcontrol-ipc/examples/generate-rpc-contract.rs; do not edit manually.\n\
         export const RPC_CONTRACT_VERSION = 1;\n\
         export type Unit = 'celsius' | 'percent' | 'bytes' | 'rpm' | 'watts' | 'volts' | 'hertz' | 'bytes_per_second' | 'frames_per_second';\n\
         export interface Device { id: string; display_name: string; family: string; vid?: number; pid?: number; serial?: string | null }\n\
         export interface Sensor { id: string; label: string; unit: Unit; value: number | null; status: string; age_ms: number | null }\n\
         export interface DisplaySettings {version:number;revision:number;temperature_unit:'celsius'|'fahrenheit';interface_language?:'ru-RU'|'en-US'}\n\
         export const RPC_METHODS = {\n",
    );
    for method in METHODS {
        let key = method.name.to_uppercase();
        output.push_str(&format!("  {key}: '{name}',\n", name = method.name));
    }
    output.push_str(
        "} as const;\nexport type RpcMethodName = typeof RPC_METHODS[keyof typeof RPC_METHODS];\n",
    );
    output
}
